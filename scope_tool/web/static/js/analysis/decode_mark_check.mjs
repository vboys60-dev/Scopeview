// 解碼三角標記：純座標、來源生命週期及實際主圖接線。
import assert from 'node:assert/strict';
import { decodeMarks, layoutRect, mount } from './mainplot.js';
import { withGrids } from './grids.js';
import { linear } from './plotcore.js';
const channels = ['OTHER', 'SCL', 'SDA'].map(name => ({ name, visible: true, scale: 1, position: 0, time_offset: 2, unit: 'V', color: '#fff' }));
const result = { base: 'SCL', summary: { channels: { scl: 'SCL', sda: 'SDA' } }, frames: [{ i: 0, t0: 3 }, { i: 7, t0: 4 }] };
const s = { channels, decodeResult: result, decodeSel: 0, view: { t0: 0, t1: 10 } };
const grids = { n: 4, assign: { OTHER: 0, SCL: 1, SDA: 2 } };
const rect = withGrids(layoutRect(800, 400), grids, channels), X = linear(0, 10, rect.l, rect.l + rect.w);
const marks = patch => decodeMarks({ ...s, ...patch }, rect, X);
for (const patch of [{ decodeSel: null }, { decodeSel: undefined }, { decodeResult: null }, { decodeSel: 99 }]) assert.deepEqual(marks(patch), []);
const one = withGrids(layoutRect(800, 400), { n: 1, assign: {} }, channels);
assert.equal(decodeMarks(s, one, X).length, 1);
assert.equal(marks()[0].x, X(5)); assert.deepEqual(marks().map(m => m.row.index), [1, 2]);
assert.equal(decodeMarks(s, withGrids(layoutRect(800, 400), { n: 2, assign: { SCL: 1, SDA: 1 } }, channels), X).length, 1);
assert.equal(marks({ channels: channels.map(c => ({ ...c, visible: false })) }).length, 2);
assert.deepEqual(marks({ channels: channels.filter(c => c.name !== 'SDA') }).map(m => m.row.index), [1]);
assert.deepEqual(marks({ channels: channels.filter(c => c.name === 'OTHER') }), []);
assert.deepEqual(marks({ channels: channels.filter(c => c.name !== 'SCL') }), []);
assert.deepEqual(marks({ decodeResult: { ...result, summary: {} } }), []);
assert.deepEqual(marks({ decodeResult: { ...result, summary: { channels: { scl: '', sda: null, data: 'MISSING' } } } }), []);
assert.deepEqual(marks({ view: { t0: 0, t1: 4 } }), []);
assert.equal(marks({ view: { t0: 4, t1: 6 } }).length, 2);
for (const view of [{ t0: 5, t1: 10 }, { t0: 0, t1: 5 }]) assert.equal(marks({ view }).length, 2);
assert.equal(marks({ channels: channels.map(c => ({ ...c, time_offset: undefined })) })[0].x, X(3));
console.log('decode_mark 座標與來源 self-check OK');
// 假畫布保留真實 save／restore 語意，記錄產品 draw 實際填色與三角路徑。
import { createStore } from './store.js';
const stack = [], fills = [];
let path = [], paints = 0, fetched = 0;
const g = new Proxy({ globalAlpha: 1 }, { get(t, k) {
  if (k === 'save') return () => stack.push({ ...t });
  if (k === 'restore') return () => { for (const key of Object.keys(t)) delete t[key]; Object.assign(t, stack.pop()); };
  if (k === 'measureText') return () => ({ width: 0 });
  if (k === 'beginPath') return () => { path = []; };
  if (k === 'moveTo' || k === 'lineTo') return (x, y) => path.push([x, y]);
  if (k === 'fill') return () => fills.push({ alpha: t.globalAlpha, color: t.fillStyle, stroke: t.strokeStyle, width: t.lineWidth, path: [...path] });
  if (k === 'fillRect') return () => { paints++; };
  return t[k] ?? (() => {});
} });
const element = () => ({ style: {}, dataset: {}, addEventListener() {}, removeEventListener() {}, append(c) { this.child = c; },
  getContext: () => g, getBoundingClientRect: () => ({ width: 800, height: 400, left: 0, top: 0 }) });
globalThis.document = { createElement: element };
globalThis.window = { devicePixelRatio: 1, addEventListener() {}, removeEventListener() {} };
globalThis.ResizeObserver = class { observe() {} disconnect() {} };
const store = createStore();
store.set({ ...s, grids, markerTable: [], file: { gen: 1, channels } });
const host = element(), mounted = mount(host, { store, bridge: { fetchWave: async () => { fetched++; return { n: 0, x: [], lo: [], hi: [], mode: 0 }; } }, ui: { toast() {} } });
const tick = () => new Promise(resolve => setTimeout(resolve, 180));
await tick();
const before = fetched, painted = paints;
store.set({ decodeSel: 7 }); assert.ok(paints > painted);
assert.equal(host.child.decodeMarks()[0].x, linear(0, 10, host.child.gridRect().l, host.child.gridRect().l + host.child.gridRect().w)(6));
await tick(); assert.equal(fetched, before);
fills.length = 0;
store.set({ decodeResult: { ...result, stale: true } });
assert.ok(host.child.decodeMarks().every(m => m.stale));
assert.ok(fills.some(f => f.alpha === .55 && f.color === '#f5b942' && f.stroke === '#000' && f.width === .8));
const triangle = fills.find(f => f.color === '#f5b942');
assert.equal(triangle.path.length, 3); assert.ok(Math.abs(triangle.path[1][0] - triangle.path[2][0] - 10) < 1e-9);
assert.ok(Math.abs(triangle.path[1][1] - triangle.path[0][1] - 10) < 1e-9);
assert.equal(g.globalAlpha, 1); assert.equal(stack.length, 0);
await tick(); assert.equal(fetched, before);
store.set({ view: { t0: 1, t1: 11 }, decodeSel: 0 }); await tick(); assert.ok(fetched > before);
store.set({ decodeResult: null }); assert.deepEqual(host.child.decodeMarks(), []); mounted.dispose();
assert.deepEqual(marks({ decodeResult: { ...result, stale: true } }).map(m => m.stale), [true, true]);
console.log('decode_mark 繪製與重畫 self-check OK');
import { reportKey, sameKey } from './report.js';
assert.equal(sameKey(reportKey(s), reportKey({ ...s, decodeSel: 7 })), false);
assert.equal(sameKey(reportKey(s), reportKey({ ...s })), true);
console.log('decode_mark 報告選取一致性 self-check OK');
